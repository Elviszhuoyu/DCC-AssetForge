# -*- coding: utf-8 -*-
"""Install the Asset Forge Blender add-on into the active Blender user scripts folder."""

from __future__ import absolute_import

import argparse
import json
import os
import shutil
import sys

ADDON_NAME = "asset_forge_extension"


def repo_root_from_script():
    return os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))


def blender_user_addons_dir(version=None):
    appdata = os.environ.get("APPDATA")
    if not appdata:
        raise RuntimeError("APPDATA is not defined; cannot locate Blender user add-ons directory.")
    if not version:
        version = "5.1"
    return os.path.join(appdata, "Blender Foundation", "Blender", version, "scripts", "addons")


def install_addon(repo_root, blender_version="5.1", user_addons_dir=""):
    repo_root = os.path.abspath(repo_root)
    source_dir = os.path.join(repo_root, "integrations", "blender", ADDON_NAME)
    if not os.path.isdir(source_dir):
        raise RuntimeError("Asset Forge Blender extension source is missing: {0}".format(source_dir))
    addons_dir = os.path.abspath(user_addons_dir or blender_user_addons_dir(blender_version))
    target_dir = os.path.join(addons_dir, ADDON_NAME)
    if os.path.isdir(target_dir):
        shutil.rmtree(target_dir)
    os.makedirs(addons_dir, exist_ok=True)
    shutil.copytree(source_dir, target_dir, ignore=shutil.ignore_patterns("__pycache__", "*.pyc"))
    write_bootstrap(target_dir, repo_root)
    return {
        "status": "success",
        "can_accept": True,
        "repo_root": repo_root.replace("\\", "/"),
        "source_dir": source_dir.replace("\\", "/"),
        "addons_dir": addons_dir.replace("\\", "/"),
        "target_dir": target_dir.replace("\\", "/"),
        "addon_name": ADDON_NAME,
        "next_action": "Enable the Asset Forge add-on in Blender, or restart Blender if preferences were saved after installation.",
    }


def write_bootstrap(target_dir, repo_root):
    path = os.path.join(target_dir, "_asset_forge_bootstrap.py")
    text = """# -*- coding: utf-8 -*-\n\"\"\"Generated by Asset Forge installer.\"\"\"\n\nfrom __future__ import absolute_import\n\nimport os\nimport sys\n\nREPO_ROOT = r\"{repo_root}\"\n\n\ndef configure():\n    root = os.path.abspath(REPO_ROOT)\n    if root not in sys.path:\n        sys.path.insert(0, root)\n    os.environ.setdefault(\"ASSET_FORGE_REPO_ROOT\", root)\n    return root\n""".format(repo_root=repo_root)
    with open(path, "w", encoding="utf-8", newline="\n") as stream:
        stream.write(text)
    return path


def main(argv=None):
    parser = argparse.ArgumentParser()
    parser.add_argument("--repo-root", default=repo_root_from_script())
    parser.add_argument("--blender-version", default="5.1")
    parser.add_argument("--user-addons-dir", default="")
    parser.add_argument("--report-path", default="")
    args = parser.parse_args(argv)
    result = install_addon(args.repo_root, args.blender_version, args.user_addons_dir)
    if args.report_path:
        parent = os.path.dirname(os.path.abspath(args.report_path))
        if parent and not os.path.isdir(parent):
            os.makedirs(parent)
        with open(args.report_path, "w", encoding="utf-8") as stream:
            json.dump(result, stream, ensure_ascii=False, indent=2, sort_keys=True)
            stream.write("\n")
    print(json.dumps(result, ensure_ascii=False, indent=2, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())